#!/usr/bin/env sh
# Nightglide source-mode installer.
#
# Installs a `nightglide` launcher into <prefix>/bin that runs the CLI from
# this repository's vendored source (vendor/omp), equivalent to the repo-root
# ./nightglide wrapper. This installer never creates or modifies any `omp`
# entry — an existing global `omp` stays untouched.
#
# Usage:
#   scripts/install.sh                # install to ~/.local/bin/nightglide
#   scripts/install.sh --prefix DIR   # install to DIR/bin/nightglide
#
# Re-running is idempotent: the launcher is regenerated in place. The script
# refuses to overwrite a file it did not generate. All checks fail fast.
set -eu
if (set -o pipefail) 2>/dev/null; then
	set -o pipefail
fi

usage() {
	cat <<'USAGE'
Usage: scripts/install.sh [--prefix DIR]

Installs a `nightglide` launcher (sh script) that runs the CLI from this
repository's vendored source: vendor/omp/packages/coding-agent/src/cli.ts.

Options:
  --prefix DIR   Install into DIR/bin/nightglide (default: ~/.local/bin)
  -v, --version  Show installer version
  -h, --help     Show this help

The installer never creates or modifies any `omp` command; an existing
global `omp` is left untouched. Re-running is idempotent.
USAGE
}

die() {
	echo "install.sh: error: $1" >&2
	exit 1
}

resolve_repo_root() {
	script_path="$0"
	while [ -L "$script_path" ]; do
		link="$(readlink "$script_path")"
		case "$link" in
		/*) script_path="$link" ;;
		*) script_path="$(dirname "$script_path")/$link" ;;
		esac
	done
	(cd "$(dirname "$script_path")/.." && pwd)
}

REPO_ROOT="$(resolve_repo_root)"

PREFIX=""
while [ $# -gt 0 ]; do
	case "$1" in
	--prefix)
		[ $# -ge 2 ] || die "--prefix requires a directory argument"
		PREFIX="$2"
		shift 2
		;;
	--prefix=*)
		PREFIX="${1#--prefix=}"
		shift
		;;
	-v | --version)
		PKG_VER="$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$REPO_ROOT/package.json" | head -n 1)"
		echo "nightglide-install/${PKG_VER:-1.0.0}"
		exit 0
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		usage >&2
		die "unknown argument: $1"
		;;
	esac
done

# Default prefix: ~/.local. Relative --prefix values are made absolute.
[ -n "$PREFIX" ] || PREFIX="$HOME/.local"
case "$PREFIX" in
/*) ;;
*) PREFIX="$(cd "$PREFIX" && pwd)" ;;
esac

BIN_DIR="$PREFIX/bin"
TARGET="$BIN_DIR/nightglide"
CLI_ENTRY="$REPO_ROOT/vendor/omp/packages/coding-agent/src/cli.ts"

echo "==> Nightglide source-mode installer"
echo "    repo:    $REPO_ROOT"
echo "    prefix:  $PREFIX"
echo "    target:  $TARGET"

# ── Pre-flight checks ────────────────────────────────────────────────────────

# 1. bun must be on PATH.
command -v bun >/dev/null 2>&1 || die "bun not found on PATH. Install Bun >= 1.4.4 (https://bun.sh) and re-run."

# 2. vendor/omp must be present (submodule initialized) with its entrypoint.
if [ ! -f "$CLI_ENTRY" ]; then
	die "vendor/omp source not found at $REPO_ROOT/vendor/omp. Run: git submodule update --init vendor/omp"
fi

# 3. Dependencies must be installed inside vendor/omp (Bun resolves the
#    workspace node_modules from there when the launcher runs).
if [ ! -d "$REPO_ROOT/vendor/omp/node_modules" ]; then
	die "vendor/omp/node_modules missing. Run: cd \"$REPO_ROOT/vendor/omp\" && bun install"
fi

# 4. Native addon (pi_natives) must be built for this platform.
OS_NAME="$(uname -s)"
ARCH_NAME="$(uname -m)"
case "$OS_NAME-$ARCH_NAME" in
Darwin-arm64) NATIVE_ID="darwin-arm64" ;;
Darwin-x86_64) NATIVE_ID="darwin-x64" ;;
Linux-x86_64) NATIVE_ID="linux-x64" ;;
Linux-aarch64 | Linux-arm64) NATIVE_ID="linux-arm64" ;;
*) NATIVE_ID="$OS_NAME-$ARCH_NAME" ;;
esac
NATIVE_LIB="$REPO_ROOT/vendor/omp/packages/natives/native/pi_natives.$NATIVE_ID.node"
NATIVE_DIR="$REPO_ROOT/vendor/omp/packages/natives/native"
if [ ! -f "$NATIVE_LIB" ]; then
	if ls "$NATIVE_DIR"/pi_natives.*.node >/dev/null 2>&1; then
		die "pi_natives native addon is built, but not for this platform ($NATIVE_ID). Run: cd \"$REPO_ROOT/vendor/omp\" && bun run build:native"
	fi
	die "pi_natives native addon not built. Run: cd \"$REPO_ROOT/vendor/omp\" && bun install && bun run build:native, then re-run install.sh"
fi

# ── Never touch an existing global omp ──────────────────────────────────────
OMP_PATH="$BIN_DIR/omp"
if [ -e "$OMP_PATH" ]; then
	echo "==> note: existing '$OMP_PATH' detected — it will NOT be read, written, or replaced."
fi

# ── Overwrite policy: regenerate only what this script generated ───────────
if [ -e "$TARGET" ] && ! grep -q "Generated by scripts/install.sh" "$TARGET" 2>/dev/null; then
	die "$TARGET already exists and was not generated by install.sh; refusing to overwrite it."
fi

# ── Write the launcher (equivalent to the repo-root ./nightglide wrapper,
#    with the repository root resolved at install time) ──────────────────────
mkdir -p "$BIN_DIR"
cat >"$TARGET" <<EOF
#!/usr/bin/env sh
# Generated by scripts/install.sh (Nightglide). Safe to overwrite by re-running
# scripts/install.sh from the source repository.
#
# Equivalent to the repo-root ./nightglide wrapper, with the repository root
# baked in at install time. Launch semantics mirror upstream's scripts/omp:
# the real cwd is stored in OMP_LAUNCH_CWD and restored in-process by the
# preload shim, and Bun is started from a bunfig-free directory so a foreign
# project's bunfig preload cannot execute inside Nightglide — this also keeps
# getProjectDir() pointing at the user's working directory, not vendor/omp.
NG_REPO_ROOT="$REPO_ROOT"
CLI="\$NG_REPO_ROOT/vendor/omp/packages/coding-agent/src/cli.ts"
PRELOAD="\$NG_REPO_ROOT/vendor/omp/packages/coding-agent/scripts/omp.ts"
[ -f "\$CLI" ] || { echo "nightglide: \$CLI not found (run 'git submodule update --init --recursive' in the repository)." >&2; exit 1; }
export PI_RAW_BIN="nightglide"
export OMP_APP_NAME="nightglide"
LAUNCH_DIR="\${OMP_DEV_LAUNCH_DIR:-\${HOME}/.omp/.dev-cwd}"
[ -d "\$LAUNCH_DIR" ] || mkdir -p "\$LAUNCH_DIR"
OMP_LAUNCH_CWD=\$PWD
export OMP_LAUNCH_CWD
cd "\$LAUNCH_DIR"
exec bun --preload "\$PRELOAD" "\$CLI" "\$@"
EOF
chmod 755 "$TARGET"

echo "==> installed: $TARGET"
echo "==> verify:    nightglide --version"
